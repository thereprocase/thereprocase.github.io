import assert from 'node:assert/strict';
import {nativeFoot,nativeGeometrySnapshot} from '../../public/gridfinity-converter/native-cad.js';
import {equivalentBrepTokens} from '../../public/gridfinity-converter/brep-equivalence.js';
import * as cad from '../../public/gridfinity-converter/vendor/replicad/replicad.js';
await nativeFoot();const oc=cad.getOC();
const source=cad.makeSphere(20).translate([5,10,15]);
source.mesh({tolerance:.025,angularTolerance:.15});
const before=source.serialize(),snapshot=nativeGeometrySnapshot(oc,source);
assert.doesNotMatch(before,/Triangulations 0\b/);
assert.match(snapshot,/Triangulations 0\b/);
assert.equal(source.serialize(),before,'snapshot must not mutate native geometry or display cache');
const reopened=cad.cast(oc.BRepToolsWrapper.Read(snapshot));
const check=new oc.BRepCheck_Analyzer(reopened.wrapped,true,false,true);
assert.equal(check.IsValid(),true);check.delete();
assert.equal(reopened.solids.length,1);
assert.equal(equivalentBrepTokens(snapshot,reopened.serialize()).equivalent,true);
assert.ok(Math.abs(cad.measureVolume(source)-cad.measureVolume(reopened))<1e-8);
const first=source.boundingBox,second=reopened.boundingBox;
assert.ok(first.bounds.every((row,i)=>row.every((value,j)=>Math.abs(value-second.bounds[i][j])<1e-9)));
first.delete();second.delete();source.delete();reopened.delete();
console.log(JSON.stringify({passed:true,meshBytes:before.length,nativeBytes:snapshot.length}));
